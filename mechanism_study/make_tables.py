"""Turn the JSON results into the numbers used by the paper, so no number is typed by hand.

Writes
  paper/lambda_sweep.dat      lambda_ent sweep on the development seed (pgfplots table)
  paper/tab_heldout.tex       held-out seeds: mean +- std per method
  paper/tab_paired.tex        held-out seeds: paired difference to HypCD
  paper/tab_designlog.tex     development seed: v0 -> v1 -> v2 design log
  paper/numbers.json          every number above, for the doc and for checking
usage: python make_tables.py [--seeds 1,2,3]
"""
import glob
import json
import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
PAPER = os.path.join(os.path.dirname(HERE), "paper", "en")
RESULTS = os.path.join(HERE, "results")
METRICS = ["all", "old", "new", "parent_acc", "novel_to_parent", "val_cluster"]
NAMES = {"gcd": "GCD (spherical)", "hypcd": "HypCD", "fourex_partition": "FourEx-style partition",
         "naive_lowpass": "Low-pass positives", "freqcone_sel": r"FreqCone ($\lambda^\star$)",
         "freqcone_w1": r"FreqCone ($\lambda_{\mathrm{ent}}{=}1$)",
         "freqcone_w0": r"FreqCone without $\mathcal{L}_{\mathrm{ent}}$ ($\lambda_{\mathrm{ent}}{=}0$)",
         "freqcone_w0.03": r"FreqCone ($\lambda_{\mathrm{ent}}{=}0.03$)", "freqcone_w0.1": r"FreqCone ($\lambda_{\mathrm{ent}}{=}0.1$)",
         "freqcone_w0.3": r"FreqCone ($\lambda_{\mathrm{ent}}{=}0.3$)"}
HELDOUT_ORDER = ["gcd", "hypcd", "fourex_partition", "naive_lowpass", "freqcone_w0", "freqcone_sel", "freqcone_w1"]


def load(pattern):
    out = {}
    for f in glob.glob(pattern):
        m = json.load(open(f))["metrics"]
        out[(m["method"], m["seed"])] = m
    return out


def fmt(v, s=None):
    return f"{v:.1f}" if s is None else f"{v:.1f}{{\\scriptsize$\\pm${s:.1f}}}"


def main(seeds):
    os.makedirs(PAPER, exist_ok=True)
    numbers = {}

    # ---- lambda sweep (development seed 0)
    sweep = sorted(load(os.path.join(RESULTS, "lambda_sweep", "*.json")).values(), key=lambda m: m["w_ent"])
    sel_path = os.path.join(RESULTS, "lambda_sweep", "selected.txt")
    selected = float(open(sel_path).read().split("=")[-1]) if os.path.exists(sel_path) else None
    if sweep:
        with open(os.path.join(PAPER, "lambda_sweep.dat"), "w") as f:
            f.write("idx lam all old new parent n2p valc selected\n")
            for i, m in enumerate(sweep):
                f.write(f"{i} {m['w_ent']} " + " ".join(f"{100 * m[k]:.2f}" for k in METRICS)
                        + f" {int(selected is not None and abs(m['w_ent'] - selected) < 1e-9)}\n")
        numbers["lambda_sweep"] = [{k: m[k] for k in METRICS + ["w_ent", "in_cone_b_u", "angle_b_u_deg", "depth_full"] if k in m}
                                   for m in sweep]
        numbers["selected_lambda"] = selected

    # ---- held-out seeds
    res = load(os.path.join(RESULTS, "results", "*.json"))
    stats = {}
    for meth in HELDOUT_ORDER:
        runs = [res[(meth, s)] for s in seeds if (meth, s) in res]
        if not runs:
            continue
        vals = {k: np.array([100 * r[k] for r in runs]) for k in METRICS}
        stats[meth] = {k: dict(mean=float(v.mean()), std=float(v.std(ddof=1)) if len(v) > 1 else 0.0,
                               per_seed=[float(x) for x in v]) for k, v in vals.items()}
        stats[meth]["n"] = len(runs)
    numbers["heldout"] = stats
    if stats:
        best = {k: max(stats[m][k]["mean"] for m in stats) for k in METRICS[:5]}
        with open(os.path.join(PAPER, "tab_heldout.tex"), "w") as f:
            f.write("% generated by make_tables.py from results/*.json\n")
            f.write("\\begin{tabular}{lccccc}\n\\toprule\n")
            f.write("Method & All & Old & New & Parent & Novel$\\to$parent \\\\\n\\midrule\n")
            for meth in [m for m in HELDOUT_ORDER if m in stats]:
                cells = []
                for k in METRICS[:5]:
                    c = fmt(stats[meth][k]["mean"], stats[meth][k]["std"])
                    cells.append(f"\\textbf{{{c}}}" if abs(stats[meth][k]["mean"] - best[k]) < 1e-9 else c)
                f.write(f"{NAMES[meth]} & " + " & ".join(cells) + " \\\\\n")
            f.write("\\bottomrule\n\\end{tabular}\n")

    # ---- held-out sensitivity to lambda_ent: every FreqCone run grouped by its weight
    by_w = {}
    for (meth, s), m in res.items():
        if meth.startswith("freqcone") and s in seeds:
            by_w.setdefault(round(m["w_ent"], 6), {})[s] = m
    sens = {}
    for w in sorted(by_w):
        runs = list(by_w[w].values())
        sens[w] = {k: dict(mean=float(np.mean([100 * r[k] for r in runs])),
                           std=float(np.std([100 * r[k] for r in runs], ddof=1)) if len(runs) > 1 else 0.0)
                   for k in METRICS}
        sens[w]["n"] = len(runs)
        hyp = [res[("hypcd", s)] for s in by_w[w] if ("hypcd", s) in res]
        if len(hyp) == len(runs):
            for k in ("all", "new", "novel_to_parent"):
                d = np.array([100 * (by_w[w][s][k] - res[("hypcd", s)][k]) for s in by_w[w]])
                sens[w][f"d_{k}"] = dict(mean=float(d.mean()), wins=int((d > 0).sum()), n=len(d))
    numbers["heldout_sensitivity"] = {f"{w:g}": v for w, v in sens.items()}
    if sens:
        with open(os.path.join(PAPER, "tab_sensitivity.tex"), "w") as f:
            f.write("% generated by make_tables.py: held-out seeds, every FreqCone weight that was run\n")
            f.write("\\begin{tabular}{lccccc}\n\\toprule\n")
            f.write("$\\lambda_{\\mathrm{ent}}$ & All & New & Parent & Novel$\\to$parent & $\\Delta$All vs.\\ HypCD \\\\\n\\midrule\n")
            for w, v in sens.items():
                lab = f"{w:g}" + (" ($\\lambda^\\star$)" if selected is not None and abs(w - selected) < 1e-9 else "")
                dall = f"{v['d_all']['mean']:+.1f} ({v['d_all']['wins']}/{v['d_all']['n']})" if "d_all" in v else "--"
                f.write(f"{lab} & " + " & ".join(fmt(v[k]["mean"], v[k]["std"]) for k in ("all", "new", "parent_acc", "novel_to_parent"))
                        + f" & {dall} \\\\\n")
            f.write("\\bottomrule\n\\end{tabular}\n")
        with open(os.path.join(PAPER, "lambda_heldout.dat"), "w") as f:
            f.write("lam all all_sd new new_sd par par_sd n2p n2p_sd n\n")
            for w, v in sens.items():
                f.write(f"{w:g} " + " ".join(f"{v[k]['mean']:.2f} {v[k]['std']:.2f}" for k in ("all", "new", "parent_acc", "novel_to_parent"))
                        + f" {v['n']}\n")

    # ---- depth regimes: is the sharp view deeper than its coarse parent? (Lemma 3)
    dev = load(os.path.join(RESULTS, "lambda_sweep", "*.json"))
    pil = load(os.path.join(RESULTS, "pilot", "*.json"))
    regimes = []
    for s in [0] + list(seeds):
        hyp = pil.get(("hypcd", 0)) if s == 0 else res.get(("hypcd", s))
        sel_run = dev.get((f"freqcone_w{selected:g}", 0)) if (s == 0 and selected is not None) else res.get(("freqcone_sel", s))
        w1_run = dev.get(("freqcone_w1", 0)) if s == 0 else res.get(("freqcone_w1", s))
        if not (hyp and sel_run and w1_run):
            continue
        row = dict(seed=s, hyp_depth=hyp["depth_full"], hyp_all=100 * hyp["all"], hyp_n2p=100 * hyp["novel_to_parent"])
        for tag, r in (("sel", sel_run), ("w1", w1_run)):
            row.update({f"{tag}_depth": r["depth_full"], f"{tag}_in_cone": 100 * r["in_cone_b_u"],
                        f"{tag}_angle": r["angle_b_u_deg"], f"{tag}_dall": 100 * (r["all"] - hyp["all"]),
                        f"{tag}_dn2p": 100 * (r["novel_to_parent"] - hyp["novel_to_parent"])})
        regimes.append(row)
    numbers["regimes"] = regimes
    if regimes:
        depth_b = 2 / np.sqrt(0.05) * np.arctanh(0.2)
        with open(os.path.join(PAPER, "tab_regimes.tex"), "w") as f:
            f.write("% generated by make_tables.py: seed 0 = development, others held out\n")
            f.write("\\begin{tabular}{lc|cccc|cccc}\n\\toprule\n")
            f.write(" & HypCD & \\multicolumn{4}{c|}{FreqCone v2, $\\lambda^\\star$} & \\multicolumn{4}{c}{FreqCone v2, $\\lambda_{\\mathrm{ent}}{=}1$} \\\\\n")
            f.write("Seed & $\\delta_c(u)$ & $\\delta_c(u)$ & in cone & $\\Delta$All & $\\Delta$N$\\to$P & $\\delta_c(u)$ & in cone & $\\Delta$All & $\\Delta$N$\\to$P \\\\\n\\midrule\n")
            for r in regimes:
                f.write(f"{r['seed']}{' (dev)' if r['seed'] == 0 else ''} & {r['hyp_depth']:.2f} & "
                        f"{r['sel_depth']:.2f} & {r['sel_in_cone']:.0f}\\% & {r['sel_dall']:+.1f} & {r['sel_dn2p']:+.1f} & "
                        f"{r['w1_depth']:.2f} & {r['w1_in_cone']:.0f}\\% & {r['w1_dall']:+.1f} & {r['w1_dn2p']:+.1f} \\\\\n")
            f.write("\\bottomrule\n\\end{tabular}\n")
        numbers["coarse_depths"] = dict(a=float(2 / np.sqrt(0.05) * np.arctanh(0.12)), b=float(depth_b))

    # ---- paired differences to HypCD
    paired = {}
    for meth in HELDOUT_ORDER:
        if meth == "hypcd":
            continue
        common = [s for s in seeds if (meth, s) in res and ("hypcd", s) in res]
        if not common:
            continue
        paired[meth] = {}
        for k in ("all", "new", "parent_acc", "novel_to_parent"):
            d = np.array([100 * (res[(meth, s)][k] - res[("hypcd", s)][k]) for s in common])
            paired[meth][k] = dict(mean=float(d.mean()), per_seed=[float(x) for x in d], wins=int((d > 0).sum()), n=len(d))
    numbers["paired_vs_hypcd"] = paired
    if paired:
        with open(os.path.join(PAPER, "tab_paired.tex"), "w") as f:
            f.write("% generated by make_tables.py\n\\begin{tabular}{lcccc}\n\\toprule\n")
            f.write("vs.\\ HypCD (same seed) & $\\Delta$All & $\\Delta$New & $\\Delta$Parent & $\\Delta$Novel$\\to$parent \\\\\n\\midrule\n")
            for meth, d in paired.items():
                cells = [f"{d[k]['mean']:+.1f} ({d[k]['wins']}/{d[k]['n']})" for k in ("all", "new", "parent_acc", "novel_to_parent")]
                f.write(f"{NAMES[meth]} & " + " & ".join(cells) + " \\\\\n")
            f.write("\\bottomrule\n\\end{tabular}\n")

    # ---- design log (development seed 0, lambda_ent = 1)
    pilot = load(os.path.join(RESULTS, "pilot", "*.json"))
    log = []
    for meth, name, change in [("hypcd", "HypCD (base)", "--"),
                               ("freqcone_v0", "FreqCone v0", "initial formulation"),
                               ("freqcone_v1", "FreqCone v1", "stop-gradient on sharp-view norm in $\\mathcal{L}_{\\mathrm{ent}}$"),
                               ("freqcone", "FreqCone v2", "fixed coarse depths; stop-gradient on $u'$ in $\\mathcal{L}_{\\mathrm{dir}}$")]:
        m = pilot.get((meth, 0))
        if m:
            log.append((name, change, m))
    numbers["design_log"] = {n: {k: m.get(k) for k in METRICS + ["depth_full"]} for n, _, m in log}
    if log:
        with open(os.path.join(PAPER, "tab_designlog.tex"), "w") as f:
            f.write("% generated by make_tables.py from pilot/*.json (seed 0)\n\\begin{tabular}{llcccc}\n\\toprule\n")
            f.write("Variant & Change & All / Old / New & Parent & Novel$\\to$parent & depth$(u)$ \\\\\n\\midrule\n")
            for name, change, m in log:
                depth = f"{m['depth_full']:.2f}" if "depth_full" in m else "--"
                f.write(f"{name} & {change} & {100 * m['all']:.1f} / {100 * m['old']:.1f} / {100 * m['new']:.1f} & "
                        f"{100 * m['parent_acc']:.1f} & {100 * m['novel_to_parent']:.1f} & {depth} \\\\\n")
            f.write("\\bottomrule\n\\end{tabular}\n")

    # ---- v3 study on fresh seeds 4-6 (results_v3/)
    v3 = load(os.path.join(RESULTS, "results_v3", "*.json"))
    v3_rows = []
    for s in (4, 5, 6):
        hyp = v3.get(("hypcd", s))
        runs = {"v2": v3.get(("freqcone_sel", s)), "v3": v3.get(("freqcone_v3_sel", s)), "v3w1": v3.get(("freqcone_v3_w1", s))}
        if not hyp or not all(runs.values()):
            continue
        row = dict(seed=s, hyp_depth=hyp["depth_full"], hyp_all=100 * hyp["all"], hyp_new=100 * hyp["new"],
                   hyp_n2p=100 * hyp["novel_to_parent"], hyp_par=100 * hyp["parent_acc"])
        for tag, r in runs.items():
            row.update({f"{tag}_depth": r["depth_full"], f"{tag}_in_cone": 100 * r["in_cone_b_u"],
                        f"{tag}_angle": r["angle_b_u_deg"], f"{tag}_all": 100 * r["all"], f"{tag}_new": 100 * r["new"],
                        f"{tag}_n2p": 100 * r["novel_to_parent"], f"{tag}_par": 100 * r["parent_acc"],
                        f"{tag}_ordered": 100 * r["frac_ordered"]})
        v3_rows.append(row)
    numbers["v3"] = v3_rows
    if v3_rows:
        with open(os.path.join(PAPER, "tab_v3.tex"), "w") as f:
            f.write("% generated by make_tables.py from results_v3/*.json (fresh seeds 4-6)\n")
            f.write("\\begin{tabular}{llccccc}\n\\toprule\n")
            f.write("Seed & Method & $\\delta_c(u)$ & in cone & All & New & Novel$\\to$parent \\\\\n\\midrule\n")
            for r in v3_rows:
                f.write(f"{r['seed']} & HypCD & {r['hyp_depth']:.2f} & -- & {r['hyp_all']:.1f} & {r['hyp_new']:.1f} & {r['hyp_n2p']:.1f} \\\\\n")
                for tag, name in (("v2", "v2, $\\lambda^\\star$"), ("v3", "v3, $\\lambda^\\star$"), ("v3w1", "v3, $\\lambda_{\\mathrm{ent}}{=}1$")):
                    f.write(f" & {name} & {r[tag + '_depth']:.2f} & {r[tag + '_in_cone']:.0f}\\% & {r[tag + '_all']:.1f} & "
                            f"{r[tag + '_new']:.1f} & {r[tag + '_n2p']:.1f} \\\\\n")
                f.write("\\midrule\n" if r is not v3_rows[-1] else "")
            f.write("\\bottomrule\n\\end{tabular}\n")

    # ---- LaTeX macros, so every number quoted in the prose also comes from the JSON files
    mname = {"all": "All", "old": "Old", "new": "New", "parent_acc": "Par", "novel_to_parent": "Ntp", "val_cluster": "Valc"}
    meth_name = {"gcd": "Gcd", "hypcd": "Hyp", "fourex_partition": "Four", "naive_lowpass": "Naive",
                 "freqcone_sel": "Sel", "freqcone_w1": "Wone", "freqcone_w0": "Wzero"}
    lines = ["% generated by make_tables.py -- do not edit by hand"]
    if selected is not None:
        lines.append(f"\\newcommand{{\\selLambda}}{{{selected:g}}}")
    for i, m in enumerate(sweep):
        tag = "abcdefgh"[i]
        lines.append(f"\\newcommand{{\\devLam{tag}}}{{{m['w_ent']:g}}}")
        for k in METRICS:
            lines.append(f"\\newcommand{{\\dev{mname[k]}{tag}}}{{{100 * m[k]:.1f}}}")
    for meth, st in stats.items():
        for k in METRICS:
            lines.append(f"\\newcommand{{\\ho{mname[k]}{meth_name[meth]}}}{{{st[k]['mean']:.1f}}}")
            lines.append(f"\\newcommand{{\\hosd{mname[k]}{meth_name[meth]}}}{{{st[k]['std']:.1f}}}")
    for meth, d in paired.items():
        for k, v in d.items():
            lines.append(f"\\newcommand{{\\d{mname[k]}{meth_name[meth]}}}{{{v['mean']:+.1f}}}")
            lines.append(f"\\newcommand{{\\w{mname[k]}{meth_name[meth]}}}{{{v['wins']}/{v['n']}}}")
    # paired differences between two methods (same seeds), quoted in the prose
    for a, b, k, name in [("freqcone_sel", "freqcone_w0", "all", "SelVsWzeroAll"),
                          ("freqcone_sel", "fourex_partition", "all", "SelVsFourAll"),
                          ("freqcone_sel", "fourex_partition", "new", "SelVsFourNew"),
                          ("freqcone_w1", "naive_lowpass", "all", "WoneVsNaiveAll"),
                          ("freqcone_w1", "naive_lowpass", "novel_to_parent", "WoneVsNaiveNtp")]:
        common = [s for s in seeds if (a, s) in res and (b, s) in res]
        if common:
            d = np.array([100 * (res[(a, s)][k] - res[(b, s)][k]) for s in common])
            lines.append(f"\\newcommand{{\\pair{name}}}{{{d.mean():+.1f}}}")
            lines.append(f"\\newcommand{{\\pairw{name}}}{{{int((d > 0).sum())}/{len(d)}}}")
            numbers.setdefault("pairs", {})[name] = dict(mean=float(d.mean()), wins=int((d > 0).sum()), n=len(d))
    if len(v3_rows) == 3:
        for tag, name in (("v2", "Vtwo"), ("v3", "Vthree"), ("v3w1", "VthreeWone")):
            for k in ("all", "new", "n2p"):
                d = np.array([r[f"{tag}_{k}"] - r[f"hyp_{k}"] for r in v3_rows])
                kk = {"all": "All", "new": "New", "n2p": "Ntp"}[k]
                lines.append(f"\\newcommand{{\\vd{kk}{name}}}{{{d.mean():+.1f}}}")
                lines.append(f"\\newcommand{{\\vw{kk}{name}}}{{{int((d > 0).sum())}/3}}")
        cones = [r["v3w1_in_cone"] for r in v3_rows]
        lines.append(f"\\newcommand{{\\VthreeConeRange}}{{{min(cones):.0f}--{max(cones):.0f}\\%}}")
        for k in ("all", "new", "n2p"):
            d = np.array([r[f"v3_{k}"] - r[f"v2_{k}"] for r in v3_rows])
            kk = {"all": "All", "new": "New", "n2p": "Ntp"}[k]
            lines.append(f"\\newcommand{{\\vd{kk}VthreeVsVtwo}}{{{d.mean():+.1f}}}")
            lines.append(f"\\newcommand{{\\vw{kk}VthreeVsVtwo}}{{{int((d > 0).sum())}/3}}")
    wtag = {0.0: "Wzero", 0.03: "Wthreec", 0.1: "Wtenc", 0.3: "Wthirtyc", 1.0: "Wone"}
    for w, v in sens.items():
        if w in wtag:
            for k in METRICS:
                lines.append(f"\\newcommand{{\\sens{mname[k]}{wtag[w]}}}{{{v[k]['mean']:.1f}}}")
            for k in ("all", "new", "novel_to_parent"):
                if f"d_{k}" in v:
                    lines.append(f"\\newcommand{{\\sensd{mname[k]}{wtag[w]}}}{{{v['d_' + k]['mean']:+.1f}}}")
                    lines.append(f"\\newcommand{{\\sensw{mname[k]}{wtag[w]}}}{{{v['d_' + k]['wins']}/{v['d_' + k]['n']}}}")
    for name, _, m in log:
        tag = {"HypCD (base)": "Hyp", "FreqCone v0": "Vzero", "FreqCone v1": "Vone", "FreqCone v2": "Vtwo"}[name]
        for k in ("all", "parent_acc", "novel_to_parent"):
            lines.append(f"\\newcommand{{\\log{mname[k]}{tag}}}{{{100 * m[k]:.1f}}}")
        if "depth_full" in m:
            lines.append(f"\\newcommand{{\\logDepth{tag}}}{{{m['depth_full']:.2f}}}")
    with open(os.path.join(PAPER, "macros.tex"), "w") as f:
        f.write("\n".join(lines) + "\n")

    with open(os.path.join(PAPER, "numbers.json"), "w") as f:
        json.dump(numbers, f, indent=1)
    print(json.dumps({"selected_lambda": numbers.get("selected_lambda"),
                      "heldout_means": {m: {k: round(v[k]["mean"], 1) for k in METRICS} for m, v in stats.items()},
                      "paired": {m: {k: round(v[k]["mean"], 1) for k in v} for m, v in paired.items()}}, indent=1))


if __name__ == "__main__":
    args = sys.argv[1:]
    seeds = [1, 2, 3]
    if "--seeds" in args:
        seeds = [int(s) for s in args[args.index("--seeds") + 1].split(",")]
    main(seeds)
